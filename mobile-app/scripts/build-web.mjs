/**
 * NEXUS Mobile App — web bundle builder.
 *
 * Capacitor serves the contents of `www/` from a `https://localhost` origin
 * inside the native WebView. The shared mobile UI (generated into
 * `public/mobile/*.html` by `packages/mobile`) is fully self-contained except
 * for one thing: it references fonts with root-relative paths
 * (`/fonts/<file>.woff2`). Root-relative URLs resolve against the WebView
 * origin, so they break in the native shell.
 *
 * This script copies the mobile HTML and the font assets into `www/` and
 * rewrites every root-relative `/fonts/...` reference to a bundle-relative
 * `fonts/...` reference. After this, the bundle is offline and fully portable.
 *
 * Source (single source of truth for the design):
 *   <repo>/public/mobile/         (HTML, generated by @nexus/mobile)
 *   <repo>/public/fonts/          (woff2 font files)
 *
 * Output:
 *   <mobile-app>/www/index.html
 *   <mobile-app>/www/fonts/*
 *   <mobile-app>/www/tr/*.html    (Turkish variant, if present)
 */
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const APP_ROOT = join(__dirname, "..");
const REPO_ROOT = join(APP_ROOT, "..");
const SRC_MOBILE = join(REPO_ROOT, "public", "mobile");
const SRC_FONTS = join(REPO_ROOT, "public", "fonts");
const OUT_DIR = join(APP_ROOT, "www");
const OUT_FONTS = join(OUT_DIR, "fonts");

if (!existsSync(SRC_MOBILE)) {
  throw new Error(`Missing mobile UI source: ${SRC_MOBILE}. Run "pnpm build:static" first.`);
}
if (!existsSync(SRC_FONTS)) {
  throw new Error(`Missing font assets: ${SRC_FONTS}.`);
}

// Start from a clean www/ so stale files never leak into the bundle.
rmSync(OUT_DIR, { recursive: true, force: true });
mkdirSync(OUT_DIR, { recursive: true });

/** Rewrite root-relative /fonts/... refs to bundle-relative fonts/... */
function rewriteAssetPaths(html) {
  // url('/fonts/...'), url("/fonts/..."), href="/fonts/..."
  return html.replace(/\/fonts\//g, "fonts/");
}

/** Copy a single HTML file (or TR variant) into www/, rewriting asset paths. */
function copyHtml(srcFile, destFile) {
  const html = readFileSync(srcFile, "utf8");
  const out = rewriteAssetPaths(html);
  mkdirSync(dirname(destFile), { recursive: true });
  writeFileSync(destFile, out, "utf8");
  return out.length;
}

// 1. Default landing page: public/mobile/index.html -> www/index.html
const indexSrc = join(SRC_MOBILE, "index.html");
const indexBytes = copyHtml(indexSrc, join(OUT_DIR, "index.html"));
console.log(`wrote www/index.html (${indexBytes} bytes)`);

// 2. Any sibling HTML pages at the mobile root (e.g. light.html) -> www/<file>
for (const name of readdirSync(SRC_MOBILE)) {
  if (name === "index.html" || !name.endsWith(".html")) continue;
  const bytes = copyHtml(join(SRC_MOBILE, name), join(OUT_DIR, name));
  console.log(`wrote www/${name} (${bytes} bytes)`);
}

// 3. Localized variants: public/mobile/tr/*.html -> www/tr/*.html
const trDir = join(SRC_MOBILE, "tr");
if (existsSync(trDir)) {
  for (const name of readdirSync(trDir)) {
    if (!name.endsWith(".html")) continue;
    const bytes = copyHtml(join(trDir, name), join(OUT_DIR, "tr", name));
    console.log(`wrote www/tr/${name} (${bytes} bytes)`);
  }
}

// 4. Fonts (woff2) -> www/fonts/
mkdirSync(OUT_FONTS, { recursive: true });
cpSync(SRC_FONTS, OUT_FONTS, { recursive: true });
const fontCount = readdirSync(OUT_FONTS).length;
console.log(`copied ${fontCount} font files -> www/fonts/`);

console.log("\nBundle ready in mobile-app/www/. Run `npx cap sync` next.");
