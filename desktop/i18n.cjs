function localize(lang, tr, en) {
  if (lang === "tr") return tr;
  if (lang === "en") return en;
  const table = MENU_STRINGS[lang];
  if (table && Object.prototype.hasOwnProperty.call(table, en)) {
    return table[en];
  }
  return MENU_STRINGS.en[en] || en;
}

function formatDevicesStatus(devices, on, lang) {
  const d = Number(devices) || 0;
  const o = Number(on) || 0;
  if (lang === "tr") return `Ev: ${d} Cihaz (${o} Açık)`;
  const template =
    (MENU_STRINGS[lang] && MENU_STRINGS[lang]["Home: {0} Devices ({1} On)"]) ||
    MENU_STRINGS.en["Home: {0} Devices ({1} On)"] ||
    "Home: {0} Devices ({1} On)";
  return template.replace("{0}", String(d)).replace("{1}", String(o));
}

function isSupportedLanguage(lang) {
  return typeof lang === "string" && /^[a-z]{2,3}(-[a-z0-9]+)?$/i.test(lang.trim());
}

