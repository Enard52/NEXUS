// Generates docs/CONNECTORS.md from the real connector registry (src/app/lan-connectors.js),
// the supported-device list (src/app/supported-devices.js) and the lan-*.test.ts files.
// Usage: node scripts/gen-connector-matrix.mjs          (writes docs/CONNECTORS.md)
// The vitest guard packages/web/src/connector-matrix.test.ts fails when the committed file is stale.
//
// HONESTY RULE (CLAUDE.md #1/#2): "Verified on real hardware" is `no` for every connector unless it is
// listed in HARDWARE_VERIFIED below. Add an id there ONLY when a real-device report is recorded in the repo
// (docs/COMPATIBILITY.md reports block / a linked issue). Automated tests are never hardware verification.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");

/** protocol id -> reference of the recorded real-device report. Currently empty: none recorded. */
export const HARDWARE_VERIFIED = {};

function loadWindow(file, withFetch) {
  const win = {};
  const src = readFileSync(resolve(ROOT, file), "utf8");
  if (withFetch)
    new Function("window", "fetch", src)(win, () => Promise.reject(new Error("no network")));
  else new Function("window", src)(win);
  return win;
}

function transport(p, availability) {
  const parts = [];
  if (p.needsUdp) parts.push("UDP bridge");
  if (p.needsTcp) parts.push("TCP bridge");
  if (p.needsTcpSession) parts.push("TCP session bridge");
  if (p.needsBinHttp) parts.push("binary HTTP bridge");
  if (!parts.length) parts.push("LAN HTTP");
  const where = availability === "desktop" ? "desktop only" : "all platforms";
  return parts.join(" + ") + ", " + where;
}

export function buildMatrix() {
  const protocols = loadWindow("src/app/lan-connectors.js", true).nexusLan.protocols;
  const groups = loadWindow("src/app/supported-devices.js", false).NEXUS_SUPPORTED_DEVICES;
  const testsDir = resolve(ROOT, "packages/web/src");
  const tests = readdirSync(testsDir)
    .filter((f) => /^lan-.*\.test\.ts$/.test(f))
    .sort()
    .map((f) => ({ name: f, text: readFileSync(resolve(testsDir, f), "utf8") }));

  const rows = protocols.map((p) => {
    const mine = groups.filter((g) => g.protocol === p.id);
    const brands = mine.length
      ? mine
          .map((g) => `${g.brand} (${g.models.length} model${g.models.length === 1 ? "" : "s"})`)
          .join(", ")
      : "not in the supported-device list";
    const availability =
      mine.length && mine.every((g) => g.availability === "desktop") ? "desktop" : "all";
    const files = tests.filter((t) => t.text.includes(`"${p.id}"`)).map((t) => t.name);
    const hw = HARDWARE_VERIFIED[p.id];
    return [
      `\`${p.id}\``,
      p.label,
      brands,
      p.caps.map((c) => `\`${c}\``).join(", "),
      transport(p, availability) +
        (p.discoverable === false ? "; added manually (not auto-discovered)" : ""),
      files.length ? "yes: " + files.map((f) => `\`${f}\``).join(", ") : "no",
      hw ? `yes: ${hw}` : "no / community testers wanted",
    ];
  });

  const head = [
    "Id",
    "Connector",
    "Brands / devices",
    "Capabilities",
    "Transport",
    "Packet/response tests",
    "Verified on real hardware",
  ];
  const lines = [
    "# Connector support matrix",
    "",
    "<!-- GENERATED by scripts/gen-connector-matrix.mjs - do not edit by hand. Run `node scripts/gen-connector-matrix.mjs`. -->",
    "",
    "This table is generated from the connector registry (`src/app/lan-connectors.js`), the supported-device list",
    "(`src/app/supported-devices.js`) and the `packages/web/src/lan-*.test.ts` files, and a test fails if it goes stale.",
    "",
    "- **Packet/response tests** means a `lan-*.test.ts` file mentions the connector id. These tests run against simulated",
    "  devices and recorded packet formats; **they are not hardware verification**.",
    "- **Verified on real hardware** is `no` unless a real-device report is recorded in this repository. Nothing is recorded yet,",
    "  so every connector says `no / community testers wanted`. If you own one of these devices, please help:",
    "  see the [live-device test program (#53 / #96)](https://github.com/Enard52/NEXUS/issues/96) and",
    "  [docs/COMPATIBILITY.md](COMPATIBILITY.md).",
    "- Want a new connector? See [docs/AUTHOR-A-CONNECTOR.md](AUTHOR-A-CONNECTOR.md).",
    "- Transport: `LAN HTTP` works everywhere; the UDP/TCP/binary/session bridges need the native transport",
    "  (desktop app or Android shell), see `docs/ARCHITECTURE.md`.",
    "",
    `| ${head.join(" | ")} |`,
    `| ${head.map(() => "---").join(" | ")} |`,
    ...rows.map((r) => `| ${r.join(" | ")} |`),
    "",
  ];
  return lines.join("\n");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(resolve(ROOT, "docs/CONNECTORS.md"), buildMatrix());
  console.log("wrote docs/CONNECTORS.md");
}
